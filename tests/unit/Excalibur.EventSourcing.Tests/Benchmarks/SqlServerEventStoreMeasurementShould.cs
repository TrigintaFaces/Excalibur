    [Fact]
    public void ExecuteAllSevenRealBenchmarksWithVerifiedResults()
    {
        var previous = Environment.GetEnvironmentVariable("BENCHMARK_SQL_CONNECTIONSTRING");
        try
        {
            Environment.SetEnvironmentVariable("BENCHMARK_SQL_CONNECTIONSTRING", database.ConnectionString);
            var artifacts = Path.Combine(Path.GetTempPath(), "oz03zn-bdn", Guid.NewGuid().ToString("N"));
            BenchmarkExecution.Run(typeof(SqlServerEventStoreBenchmarks).Assembly, [
                "--filter", "*SqlServerEventStoreBenchmarks*", "--artifacts", artifacts,
                "--warmupCount", "1", "--iterationCount", "1",
            ]).ShouldBe(0);
            var report = Directory.GetFiles(Path.Combine(artifacts, "results"), "*-report.csv").ShouldHaveSingleItem();
            var rows = File.ReadAllLines(report);
            rows.Length.ShouldBe(8);
            var meanIndex = Array.IndexOf(rows[0].Split(','), "Mean");
            meanIndex.ShouldBeGreaterThanOrEqualTo(0);
            rows.Skip(1).All(row => row.Split(',')[meanIndex] != "NA").ShouldBeTrue();
        }
        finally
        {
            Environment.SetEnvironmentVariable("BENCHMARK_SQL_CONNECTIONSTRING", previous);
        }
    }

    [Fact]
    public async Task CleanOwnedSchemaWhenSeedingFailsBeforeAnEngineExists()
    {
        var benchmark = CreateBenchmark();
        var triggerName = $"RejectSeed_{Guid.NewGuid():N}";
        await ExecuteSqlAsync($"""
            CREATE TRIGGER [{triggerName}] ON DATABASE FOR CREATE_TABLE AS
            BEGIN
                SET NOCOUNT ON;
                IF EVENTDATA().value('(/EVENT_INSTANCE/SchemaName)[1]', 'nvarchar(128)') = N'{benchmark.SchemaName}'
                   AND EVENTDATA().value('(/EVENT_INSTANCE/ObjectName)[1]', 'nvarchar(128)') = N'EventStoreEvents'
                    ALTER TABLE [{benchmark.SchemaName}].[EventStoreEvents] ADD CONSTRAINT RejectSeeds CHECK ([Version] < 0);
            END;
            """);
        try
        {
            var error = await Should.ThrowAsync<InvalidOperationException>(benchmark.GlobalSetup);
            error.Message.ShouldContain("Committed");
            // Deliberately do not invoke GlobalCleanup: failed setup must release its own resources.
            await ExecuteSqlAsync($"IF SCHEMA_ID('{benchmark.SchemaName}') IS NOT NULL THROW 51000, 'Failed setup leaked schema', 1;");
        }
        finally
        {
            await ExecuteSqlAsync($"DROP TRIGGER [{triggerName}] ON DATABASE;");
        }
    }

    [Fact]
    public async Task SeedExactStreamsAndSnapshotWithoutTouchingCallerTables()
    {
        await ExecuteSqlAsync("IF OBJECT_ID('dbo.BenchmarkCallerData') IS NULL CREATE TABLE dbo.BenchmarkCallerData (Id int NOT NULL);");
        var benchmark = CreateBenchmark();
        try
        {
            await benchmark.GlobalSetup();
            await using var connection = new SqlConnection(database.ConnectionString);
            await connection.OpenAsync();
#pragma warning disable CA2100 // Schema generated by the benchmark, never external input.
            await using var counts = new SqlCommand($"""
                SELECT COUNT_BIG(*), COUNT(DISTINCT [AggregateId]), MIN([Version]), MAX([Version])
                FROM [{benchmark.SchemaName}].[EventStoreEvents];
                """, connection);
#pragma warning restore CA2100
            await using var reader = await counts.ExecuteReaderAsync();
            (await reader.ReadAsync()).ShouldBeTrue();
            reader.GetInt64(0).ShouldBe(555);
            reader.GetInt32(1).ShouldBe(3);
            reader.GetInt64(2).ShouldBe(0);
            reader.GetInt64(3).ShouldBe(499);
            benchmark.IterationSetup();
            var snapshot = await benchmark.LoadSnapshot();
            snapshot.ShouldNotBeNull();
            snapshot.Version.ShouldBe(4);
            snapshot.Data.Length.ShouldBe(512);
            await benchmark.IterationCleanup();
        }
        finally
        {
            await benchmark.GlobalCleanup();
        }

        await ExecuteSqlAsync("IF OBJECT_ID('dbo.BenchmarkCallerData') IS NULL THROW 51000, 'Caller table was removed', 1;");
        await ExecuteSqlAsync($"IF SCHEMA_ID('{benchmark.SchemaName}') IS NOT NULL THROW 51000, 'Benchmark schema leaked', 1;");
    }

