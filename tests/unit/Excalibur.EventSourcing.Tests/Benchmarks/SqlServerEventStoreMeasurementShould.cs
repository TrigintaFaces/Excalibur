    [Fact]
    public async Task PreservePersistedPositionsAcrossInterleavedTenantsAndArchivedRows()
    {
        var benchmark = CreateBenchmark();
        try
        {
            await benchmark.GlobalSetup();
            var aggregateId = Guid.NewGuid().ToString("N");
            SqlServerEventStore Store(string tenant)
            {
                var context = A.Fake<ITenantContext>();
                A.CallTo(() => context.TenantId).Returns(tenant);
                A.CallTo(() => context.HasTenant).Returns(true);
                return new SqlServerEventStore(() => new SqlConnection(database.ConnectionString),
                    NullLogger<SqlServerEventStore>.Instance, tenantContext: context, schema: benchmark.SchemaName);
            }

            Excalibur.Benchmarks.EventSourcing.TestDomainEvent Event(long version) => new()
            {
                AggregateId = aggregateId, EventId = Guid.NewGuid().ToString("N"), Version = version,
                OccurredAt = DateTimeOffset.UtcNow, EventType = "TestDomainEvent", Data = "position-regression",
            };
            var tenantA = Store("tenant-a");
            var tenantB = Store("tenant-b");
            (await tenantA.AppendAsync(aggregateId, "PositionRegression", [Event(0)], -1, CancellationToken.None)).Outcome
                .ShouldBe(AppendOutcome.Committed);
            (await tenantB.AppendAsync(aggregateId, "PositionRegression", [Event(0)], -1, CancellationToken.None)).Outcome
                .ShouldBe(AppendOutcome.Committed);
            var archived = Event(2);
            (await tenantA.AppendAsync(aggregateId, "PositionRegression", [Event(1), archived], 0, CancellationToken.None)).Outcome
                .ShouldBe(AppendOutcome.Committed);
            await using var connection = new SqlConnection(database.ConnectionString);
            await connection.OpenAsync();
#pragma warning disable CA2100 // Generated schema; event identifier is a bound parameter.
            await using var query = new SqlCommand($"""
                UPDATE [{benchmark.SchemaName}].[EventStoreEvents] SET ArchivedAt = SYSDATETIMEOFFSET(), EventData = NULL
                WHERE EventId = @EventId;
                SELECT Position FROM [{benchmark.SchemaName}].[EventStoreEvents] WHERE EventId = @EventId;
                """, connection);
#pragma warning restore CA2100
            _ = query.Parameters.AddWithValue("@EventId", archived.EventId);
            var persistedPosition = (long)(await query.ExecuteScalarAsync())!;

            var result = (await tenantA.LoadAsync(aggregateId, "PositionRegression", 1, CancellationToken.None)).ShouldHaveSingleItem();
            result.EventId.ShouldBe(archived.EventId);
            result.Version.ShouldBe(2);
            result.GlobalPosition.ShouldBe(persistedPosition);
            result.GlobalPosition.ShouldBeGreaterThan(result.Version + 1);
            result.ArchivedAt.ShouldNotBeNull();
            result.EventData.ShouldBeNull();
            (await tenantB.LoadAsync(aggregateId, "PositionRegression", CancellationToken.None)).ShouldHaveSingleItem().Version.ShouldBe(0);
        }
        finally
        {
            await benchmark.GlobalCleanup();
        }
    }

    [Fact]
