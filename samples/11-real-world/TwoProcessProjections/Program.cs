using Excalibur.EventSourcing.SqlServer;
using Excalibur.Examples.TwoProcessProjections;

using Microsoft.Data.SqlClient;

// A web API and a background jobs service against ONE database, which is what an on-premises
// deployment usually looks like. Run the same project twice:
//
//     dotnet run -- api      the web API. Drives projections itself; no background poller.
//     dotnet run -- jobs     the jobs service. Runs the projection host.
//
// The roles differ in exactly one registration (see SampleRegistration). Everything else is shared
// on purpose, because the behaviour under demonstration comes from the TOPOLOGY, not the domain.
var role = args.Length > 0 ? args[0].ToLowerInvariant() : "api";
if (role is not ("api" or "jobs"))
{
	await Console.Error.WriteLineAsync("Usage: dotnet run -- [api|jobs]").ConfigureAwait(false);
	return 1;
}

var builder = WebApplication.CreateBuilder(args);

var connectionString = builder.Configuration.GetConnectionString("EventStore")
	?? "Server=localhost;Database=ExcaliburTwoProcessSample;Trusted_Connection=True;TrustServerCertificate=True";

_ = builder.Services.AddSample(connectionString, role);

var app = builder.Build();

// Create the projection table from the SHIPPED script rather than a hand-written copy. A sample is
// the one place a consumer copies DDL from, so getting it wrong here is worse than getting it wrong
// in the framework: their database, their outage, and no gate of ours can see it.
await using (var connection = new SqlConnection(connectionString))
{
	await connection.OpenAsync().ConfigureAwait(false);
	await using var command = connection.CreateCommand();

	// CA2100 is suppressed rather than worked around: the text is DDL generated by the provider from a
	// compile-time constant table name, and CreateTableScript refuses any identifier that is not
	// letters, digits or underscores for exactly this reason. There is no parameterised form of
	// this DDL to prefer, and nothing here reaches user input.
#pragma warning disable CA2100
	command.CommandText = SqlServerProjectionSchema.CreateTableScript(
        Excalibur.EventSourcing.ProjectionVersionConvention.Qualify("SampleOrderSummary", typeof(OrderSummary), '_'));
#pragma warning restore CA2100
	_ = await command.ExecuteNonQueryAsync().ConfigureAwait(false);
}

app.MapSample(role);
app.MapHealthChecks("/health");

await Console.Out.WriteLineAsync(
	$"Running as '{role}'. Projection host: {(role == "jobs" ? "ENABLED" : "not registered")}.")
	.ConfigureAwait(false);

await app.RunAsync().ConfigureAwait(false);
return 0;
