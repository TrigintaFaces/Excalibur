-- Oracle ordinary timer receiver v1. STATE metadata is separate script02.
-- Defaults DISPATCH.SAGATIMEOUTS; adapt ALL owner/table occurrences for a configured direct payload table.
-- No runtime DDL. DDL implicitly commits; runtime refuses partial schema. Preserve compact authority
-- after payload retirement/state purge. No TTL/global quota/automatic eviction.
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
DECLARE
    n NUMBER;
    PROCEDURE ensure_table(p_name VARCHAR2,p_sql VARCHAR2) IS
    BEGIN
        SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='DISPATCH' AND TABLE_NAME=p_name;
        IF n=0 THEN
            BEGIN EXECUTE IMMEDIATE p_sql;
            EXCEPTION WHEN OTHERS THEN IF SQLCODE<>-955 THEN RAISE; END IF; END;
        END IF;
    END;
    PROCEDURE ensure_column(p_name VARCHAR2,p_type VARCHAR2) IS
    BEGIN
        SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS WHERE OWNER='DISPATCH' AND TABLE_NAME='SAGATIMEOUTS' AND COLUMN_NAME=p_name;
        IF n=0 THEN
            BEGIN EXECUTE IMMEDIATE 'ALTER TABLE DISPATCH.SAGATIMEOUTS ADD ('||p_name||' '||p_type||')';
            EXCEPTION WHEN OTHERS THEN IF SQLCODE<>-1430 THEN RAISE; END IF; END;
        END IF;
    END;
    PROCEDURE ensure_index(p_name VARCHAR2,p_sql VARCHAR2) IS
    BEGIN
        SELECT COUNT(*) INTO n FROM ALL_INDEXES WHERE OWNER='DISPATCH' AND INDEX_NAME=p_name;
        IF n=0 THEN
            BEGIN EXECUTE IMMEDIATE p_sql;
            EXCEPTION WHEN OTHERS THEN IF SQLCODE<>-955 THEN RAISE; END IF; END;
        END IF;
    END;
BEGIN
    ensure_table('SAGATIMERRECOVERYTARGETS',q'[CREATE TABLE DISPATCH.SAGATIMERRECOVERYTARGETS (TargetId RAW(16) NOT NULL, OwnerName VARCHAR2(128 CHAR) NOT NULL, TableName VARCHAR2(128 CHAR) NOT NULL,
ObjectId NUMBER(19) NOT NULL, DataObjectId NUMBER(19) NOT NULL, SchemaVersion NUMBER(1) DEFAULT 1 NOT NULL,
CONSTRAINT PK_STRT PRIMARY KEY(TargetId), CONSTRAINT UQ_STRT_OBJECT UNIQUE(ObjectId,DataObjectId), CONSTRAINT CK_STRT_VERSION CHECK(SchemaVersion=1))]');
    ensure_table('SAGATIMERRECOVERYSCOPES',q'[CREATE TABLE DISPATCH.SAGATIMERRECOVERYSCOPES (ScopeId RAW(16) NOT NULL, TargetId RAW(16) NOT NULL, TenantKey RAW(32) NOT NULL, TenantBytes RAW(256) NOT NULL,
SagaGuid RAW(16) NOT NULL, Token RAW(16) NOT NULL, IncarnationId RAW(16) NOT NULL, SequenceNumber NUMBER(19) DEFAULT 0 NOT NULL,
MutationRevision NUMBER(19) DEFAULT 0 NOT NULL, StateType NVARCHAR2(500) NULL, BatchId RAW(16) NULL, ExpectedFence RAW(16) NULL,
ObservedRevision NUMBER(19) NULL, Digest RAW(32) NULL, CancelAllThrough NUMBER(19) DEFAULT -1 NOT NULL, CancelAllRevision NUMBER(19) DEFAULT 0 NOT NULL,
CONSTRAINT PK_STRS PRIMARY KEY(ScopeId), CONSTRAINT UQ_STRS_DOMAIN UNIQUE(TargetId,TenantKey,SagaGuid),
CONSTRAINT FK_STRS_TARGET FOREIGN KEY(TargetId) REFERENCES DISPATCH.SAGATIMERRECOVERYTARGETS(TargetId),
CONSTRAINT CK_STRS_NUMBERS CHECK(SequenceNumber>=0 AND MutationRevision>=0 AND CancelAllThrough>=-1 AND CancelAllRevision>=0))]');
    ensure_table('SAGATIMERRECOVERYTIMERS',q'[CREATE TABLE DISPATCH.SAGATIMERRECOVERYTIMERS (ScopeId RAW(16) NOT NULL, TargetId RAW(16) NOT NULL, IdKey RAW(32) NOT NULL, IdBytes RAW(2000) NOT NULL,
Tracked NUMBER(1) NOT NULL, IncarnationId RAW(16) NULL, SequenceNumber NUMBER(19) NULL, StateType NVARCHAR2(500) NULL,
CreatedRevision NUMBER(19) NOT NULL, IsCancelled NUMBER(1) NOT NULL, CancelThrough NUMBER(19) DEFAULT -1 NOT NULL, CancelRevision NUMBER(19) DEFAULT 0 NOT NULL,
CONSTRAINT PK_STRI PRIMARY KEY(ScopeId,IdKey), CONSTRAINT FK_STRI_SCOPE FOREIGN KEY(ScopeId) REFERENCES DISPATCH.SAGATIMERRECOVERYSCOPES(ScopeId),
CONSTRAINT FK_STRI_TARGET FOREIGN KEY(TargetId) REFERENCES DISPATCH.SAGATIMERRECOVERYTARGETS(TargetId),
CONSTRAINT CK_STRI_FLAGS CHECK(Tracked IN(0,1) AND IsCancelled IN(0,1)),
CONSTRAINT CK_STRI_NUMBERS CHECK(CreatedRevision>=-1 AND CancelThrough>=-1 AND CancelRevision>=0),
CONSTRAINT CK_STRI_OWNED CHECK((Tracked=0) OR (IncarnationId IS NOT NULL AND SequenceNumber>0 AND StateType IS NOT NULL)))]');
    ensure_table('SAGATIMERRECOVERYTOKENS',q'[CREATE TABLE DISPATCH.SAGATIMERRECOVERYTOKENS (ScopeId RAW(16) NOT NULL, Token RAW(16) NOT NULL, CONSTRAINT PK_STRK PRIMARY KEY(ScopeId,Token),
CONSTRAINT FK_STRK_SCOPE FOREIGN KEY(ScopeId) REFERENCES DISPATCH.SAGATIMERRECOVERYSCOPES(ScopeId))]');
    ensure_table('SAGATIMERRECOVERYRESULTS',q'[CREATE TABLE DISPATCH.SAGATIMERRECOVERYRESULTS (ScopeId RAW(16) NOT NULL, IntentOrdinal NUMBER(10) NOT NULL, ActionKind NUMBER(1) NOT NULL,
IdBytes RAW(2000) NULL, OutcomeKind NUMBER(1) NOT NULL, AuthorityRevision NUMBER(19) NOT NULL,
CONSTRAINT PK_STRR PRIMARY KEY(ScopeId,IntentOrdinal), CONSTRAINT FK_STRR_SCOPE FOREIGN KEY(ScopeId) REFERENCES DISPATCH.SAGATIMERRECOVERYSCOPES(ScopeId),
CONSTRAINT CK_STRR_KINDS CHECK(IntentOrdinal>=0 AND ActionKind IN(1,2,3) AND OutcomeKind IN(0,1,2) AND AuthorityRevision>=0),
CONSTRAINT CK_STRR_ID CHECK((ActionKind=3 AND IdBytes IS NULL) OR (ActionKind IN(1,2) AND IdBytes IS NOT NULL)))]');
    ensure_column('OWNEDINCARNATIONID','RAW(16) NULL');
    ensure_column('OWNEDGENERATION','NUMBER(19) NULL');
    ensure_column('OWNEDSTATETYPE','NVARCHAR2(500) NULL');
    ensure_column('RECOVERYSAGAGUID','RAW(16) NULL');
    ensure_index('UX_STRI_TRACKED',q'[CREATE UNIQUE INDEX DISPATCH.UX_STRI_TRACKED ON DISPATCH.SAGATIMERRECOVERYTIMERS(CASE WHEN Tracked=1 THEN TargetId ELSE NULL END,CASE WHEN Tracked=1 THEN IdKey ELSE NULL END)]');
    ensure_index('IX_STRT_DOMAIN',q'[CREATE INDEX DISPATCH.IX_STRT_DOMAIN ON DISPATCH.SAGATIMEOUTS(TenantId,RecoverySagaGuid)]');
    BEGIN
        EXECUTE IMMEDIATE q'[INSERT INTO DISPATCH.SAGATIMERRECOVERYTARGETS(TargetId,OwnerName,TableName,ObjectId,DataObjectId,SchemaVersion)
        SELECT SYS_GUID(),o.OWNER,o.OBJECT_NAME,o.OBJECT_ID,NVL(o.DATA_OBJECT_ID,0),1
        FROM ALL_OBJECTS o WHERE o.OWNER='DISPATCH' AND o.OBJECT_NAME='SAGATIMEOUTS' AND o.OBJECT_TYPE='TABLE'
        AND NOT EXISTS(SELECT 1 FROM DISPATCH.SAGATIMERRECOVERYTARGETS t WHERE t.ObjectId=o.OBJECT_ID AND t.DataObjectId=NVL(o.DATA_OBJECT_ID,0))]';
    EXCEPTION WHEN DUP_VAL_ON_INDEX THEN NULL;
    END;
    EXECUTE IMMEDIATE q'[SELECT COUNT(*) FROM DISPATCH.SAGATIMERRECOVERYTARGETS t JOIN ALL_OBJECTS o
      ON t.ObjectId=o.OBJECT_ID AND t.DataObjectId=NVL(o.DATA_OBJECT_ID,0)
      WHERE o.OWNER='DISPATCH' AND o.OBJECT_NAME='SAGATIMEOUTS' AND o.OBJECT_TYPE='TABLE' AND t.SchemaVersion=1]' INTO n;
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20004,'Register exactly one selected direct Oracle timer table.'); END IF;
END;
