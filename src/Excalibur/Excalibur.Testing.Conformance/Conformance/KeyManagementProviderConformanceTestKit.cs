			}

			// Act — reactivate.
			var result = await admin.ReactivateKeyAsync(keyId, CancellationToken.None).ConfigureAwait(false);

			// Assert
			if (!result)
			{
				throw new TestFixtureAssertionException("Expected ReactivateKeyAsync to return true for an existing key.");
			}

