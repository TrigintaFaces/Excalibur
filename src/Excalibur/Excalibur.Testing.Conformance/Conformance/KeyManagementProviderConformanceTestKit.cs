				.RotateKeyAsync(keyId, EncryptionAlgorithm.Aes256Gcm, null, null, CancellationToken.None)
				.ConfigureAwait(false);

			const string NeverHeld = "0f1e2d3c4b5a69788796a5b4c3d2e1f0";

