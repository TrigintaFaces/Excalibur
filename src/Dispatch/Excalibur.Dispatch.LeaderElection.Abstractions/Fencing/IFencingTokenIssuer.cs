namespace Excalibur.Dispatch.LeaderElection.Fencing;

/// <summary>Advances authoritative fencing marks, in addition to observing and validating them.</summary>
/// <remarks>
/// Only providers that perform the mint implement this capability. Reading a native ownership counter
/// is not minting. A reader need not implement this interface; callers that mint require it explicitly.
/// This does not promise the mint and leadership acquisition share one transaction.
/// </remarks>
public interface IFencingTokenIssuer : IFencingTokenProvider
{
    /// <summary>Atomically generates a strictly positive token greater than prior tokens for this resource.</summary>
    /// <param name="resourceId">The nonblank protected resource identifier.</param>
    /// <param name="cancellationToken">The cancellation token to observe.</param>
    /// <returns>The token generated by this operation.</returns>
    /// <remarks>
    /// All contenders share the same resource authority and retained counter history required by
    /// IFencingTokenProvider. Store/consistency faults propagate without conversion to an absent mark;
    /// caller cancellation is honored before store access. Minting generates a mark; it does not grant a lease.
    /// Growth is ordered at generation in the authoritative store, not by asynchronous return order.
    /// Concurrent mints never generate the same token. A paused response may return after a later mint.
    /// Failure or cancellation does not prove rollback: an actually generated mark may be observed by
    /// GetTokenAsync even when this call did not deliver its result. Never rewind or fabricate a mark.
    /// </remarks>
    /// <exception cref="ArgumentException">The resource identifier is null, empty or whitespace.</exception>
    /// <exception cref="OperationCanceledException">Cancellation was observed.</exception>
    /// <exception cref="FencingTokenExhaustedException">No strictly positive token remains; the domain never wraps.</exception>
    ValueTask<long> IssueTokenAsync(string resourceId, CancellationToken cancellationToken);
}
